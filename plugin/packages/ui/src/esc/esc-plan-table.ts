/**
 * [INPUT]: 只依赖标准库的 `Map`；不依赖 React、不依赖任何兄弟叶、不发请求、不认识任何路由 / DTO
 * [OUTPUT]: 对外提供**唯一**一枚计划表构造器 `enterpriseEscPlanTable`（同一枚键取两次 ⇒ **同一个对象**）
 * [POS]: esc 技能页"逐卡新造的对象"收成"按数据 + 状态构造一次"的**唯一实现**；它同时是"卡片 memo
 *   真的能生效"这件事在**纯函数级**可直调取证的那一处 —— `esc-card.tsx` 的 `EnterpriseEscCard`
 *   由 `memo` 包着，而 memo 的判据是 **props 逐键浅相等** ⇒ 卡片那三份计划（`install` / `more` /
 *   `tryNow`）**必须**是同一枚对象，否则每渲染一次就换一份新引用，memo 每次都判"变了"、几百张卡
 *   照旧整树重画（真机上"技能页很卡 / hover 也卡"的主因之一）。
 *
 *   ★**为什么 `useMemo` 不够、本叶还非有不可**（两层，缺一不可）：
 *     · `useMemo` 管的是"**依赖没变就不要重建这张表**"——它给的是**表**的引用稳定；
 *     · 本叶管的是"**表内同一枚键永远是同一枚对象**"——它给的是**表里那一格**的引用稳定。
 *   少了后者，表每次被问到同一枚技能都要重跑一遍构造（自装集合的成员判定、四条端口在不在场、
 *   在途与失败五件事实），而且给出的是**新对象**，memo 照样每次都判"变了"。
 *   ★**为什么值得单开一叶**：三张表（`try` / `more` / `install`）要的都是"一输入一结果 + 引用稳定"，
 *     把它抄三遍就是三处迟早会漂的缓存实现（本仓最不肯留的那种口子）；收成一叶之后，
 *     "同键同对象"这条性质**只有一处实现**、也只有一处需要证明。
 *   ★**它是纯的**：一个 `Map` + 一枚构造闭包，没有 React、没有副作用、没有全局状态、不缓存到模块级
 *     ⇒ 同一张表取两次（＝同一份数据 + 同一份状态下的两次"渲染"）逐键引用相等这件事，
 *     可以在 vitest 里**直调取证**（那正是 `tests/esc-plan-reference.spec.ts` 的锁）。
 * [PROTOCOL]: 变更时更新此头部，然后检查 CLAUDE.md
 */

/**
 * 一张**同一输入 ⇒ 同一引用**的计划表（纯函数，可直调）。
 *
 * @param build - 某一枚键的构造式；**只在这一枚键第一次被取到时跑一次**。
 * @returns `get(key)`：同一枚键取两次拿到**同一个对象**（含"这一枚没有计划"这个结论本身）。
 */
export function enterpriseEscPlanTable<K, V>(build: (key: K) => V): (key: K) => V {
  /**
   * 命中判定用 `has` 而**不是** `get(key) !== undefined`：**"这一枚没有计划"也是一个结论**
   * （`more` 那一档的 `undefined` 就是"这张卡连 `⋯` 都不画"），拿 `undefined` 当"未命中"
   * 会让那条判据每渲染一次重跑一遍——而那正是本叶要消掉的白算。
   */
  const cache = new Map<K, V>()
  return key => {
    if (cache.has(key)) return cache.get(key) as V
    const made = build(key)
    cache.set(key, made)
    return made
  }
}
